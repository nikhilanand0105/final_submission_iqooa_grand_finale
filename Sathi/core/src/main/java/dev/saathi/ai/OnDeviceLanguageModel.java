package dev.saathi.ai;

/**
 * Provider interface for on-device language models (LiteRT-LM Gemma).
 * Accepts ONLY structured indicators and explicitly chosen text.
 * Returns strongly typed results.
 */
public interface OnDeviceLanguageModel extends AutoCloseable {

    /**
     * Current lifecycle state of the model engine.
     */
    ModelLifecycleState getState();

    /**
     * Current human-readable status message.
     */
    String getStatusMessage();

    /**
     * Absolute path of the model file if loaded.
     */
    String getModelPath();

    /**
     * Returns the name of the active hardware acceleration backend (e.g., GPU, CPU, NPU).
     */
    String getBackendName();

    /**
     * Initializes the model on a background worker thread.
     */
    void initializeAsync(ModelInitCallback callback);

    /**
     * Synthesizes an on-device contextual explanation for verified security findings.
     */
    void explainFindingAsync(SecurityFindingContext context, ExplanationCallback callback);

    /**
     * Answers a specific conversational security question about the active finding or general safety.
     */
    void answerQueryAsync(String userQuestion, SecurityFindingContext context, ExplanationCallback callback);

    /**
     * Resets the active conversation session to a fresh state (clears multi-turn history).
     */
    void resetConversation();

    /**
     * Cancels active inference on the native runtime if currently executing.
     */
    void cancelInference();

    /**
     * Releases model and conversation native memory.
     */
    @Override
    void close();

    interface ModelInitCallback {
        void onStateChanged(ModelLifecycleState state, String message);
    }

    interface ExplanationCallback {
        void onSuccess(ExplanationResult result);
        void onError(Throwable throwable, ExplanationResult fallbackResult);

        /**
         * Called when a partial token chunk is generated by the local model.
         * Enables real-time on-device streaming to the UI.
         */
        default void onPartialToken(String tokenChunk) {}
    }
}
